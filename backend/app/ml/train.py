"""Train and evaluate the student-state classifier.

Run:  python -m app.ml.train
Writes models/state_model.joblib and models/model_card.json (metrics, dataset, version).

Procedure:
 1. Generate 3000 synthetic students (documented in synthetic.py).
 2. Stratified 75/25 train/test split (test set is never used for model selection).
 3. Model selection: 5-fold stratified cross-validation on the TRAINING set only, comparing
    Random Forest against Logistic Regression, a single Decision Tree and a majority baseline,
    using macro-F1.
 4. The Random Forest (the agreed model) is fitted on the full training set and evaluated
    once on the held-out test set: accuracy, precision, recall, F1, confusion matrix, ROC-AUC.
"""
import json
from datetime import datetime, timezone

import joblib
import numpy as np
from sklearn.dummy import DummyClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (accuracy_score, classification_report, confusion_matrix, f1_score,
                             precision_score, recall_score, roc_auc_score)
from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.tree import DecisionTreeClassifier

from ..config import MODEL_DIR
from .features import FEATURE_NAMES
from .synthetic import LABELS, generate_students

MODEL_VERSION = "rf-synth-1.0"
N_STUDENTS = 3000
SEED = 42


def rf_pipeline():
    return Pipeline([
        ("impute", SimpleImputer(strategy="median", add_indicator=True)),
        ("clf", RandomForestClassifier(n_estimators=300, max_depth=8, min_samples_leaf=5,
                                       class_weight="balanced", random_state=SEED, n_jobs=-1)),
    ])


def candidates():
    imp = lambda: SimpleImputer(strategy="median", add_indicator=True)  # noqa: E731
    return {
        "random_forest": rf_pipeline(),
        "logistic_regression": Pipeline([("impute", imp()), ("scale", StandardScaler()),
                                         ("clf", LogisticRegression(max_iter=2000, class_weight="balanced"))]),
        "decision_tree": Pipeline([("impute", imp()),
                                   ("clf", DecisionTreeClassifier(max_depth=5, class_weight="balanced",
                                                                  random_state=SEED))]),
        "majority_baseline": Pipeline([("impute", imp()), ("clf", DummyClassifier(strategy="most_frequent"))]),
    }


def train(out_dir=MODEL_DIR, verbose=True) -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    df = generate_students(N_STUDENTS, seed=SEED)
    X, y = df[FEATURE_NAMES], df["label"]
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.25, stratify=y, random_state=SEED)

    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
    selection = {}
    for name, pipe in candidates().items():
        scores = cross_val_score(pipe, X_tr, y_tr, cv=cv, scoring="f1_macro")
        selection[name] = {"cv_f1_macro_mean": round(float(scores.mean()), 4),
                           "cv_f1_macro_std": round(float(scores.std()), 4)}

    model = rf_pipeline().fit(X_tr, y_tr)
    pred = model.predict(X_te)
    proba = model.predict_proba(X_te)
    classes = list(model.classes_)
    importances = model.named_steps["clf"].feature_importances_[: len(FEATURE_NAMES)]

    metrics = {
        "accuracy": round(accuracy_score(y_te, pred), 4),
        "precision_macro": round(precision_score(y_te, pred, average="macro"), 4),
        "recall_macro": round(recall_score(y_te, pred, average="macro"), 4),
        "f1_macro": round(f1_score(y_te, pred, average="macro"), 4),
        "roc_auc_ovr_macro": round(roc_auc_score(y_te, proba, multi_class="ovr", average="macro",
                                                 labels=classes), 4),
        "confusion_matrix": {"labels": LABELS,
                             "matrix": confusion_matrix(y_te, pred, labels=LABELS).tolist()},
        "per_class": classification_report(y_te, pred, labels=LABELS, output_dict=True, zero_division=0),
    }
    card = {
        "model_version": MODEL_VERSION,
        "trained_at": datetime.now(timezone.utc).isoformat(),
        "algorithm": "RandomForestClassifier (scikit-learn) with median imputation + missing indicators",
        "dataset": {
            "source": "SYNTHETIC - generated by app/ml/synthetic.py (seed 42). Not real student data.",
            "n_students": N_STUDENTS, "train_size": len(X_tr), "test_size": len(X_te),
            "split": "stratified 75/25 hold-out; model selection by 5-fold CV on train only",
            "class_distribution": y.value_counts().to_dict(),
            "label_definition": "End-of-term outcome (hidden) >=60 normal; 45-60 attention_needed; <45 high_support_need",
            "missing_rate_per_optional_feature": 0.08,
        },
        "features": FEATURE_NAMES,
        "classes": classes,
        "feature_importance": {f: round(float(i), 4) for f, i in zip(FEATURE_NAMES, importances)},
        "training_medians": {f: round(float(np.nanmedian(X_tr[f])), 2) for f in FEATURE_NAMES},
        "model_selection_cv": selection,
        "test_metrics": metrics,
        "disclaimer": ("Synthetic-data evaluation only. These numbers show the pipeline works; "
                       "they are not evidence of real-world predictive accuracy."),
    }
    joblib.dump({"pipeline": model, "version": MODEL_VERSION, "features": FEATURE_NAMES},
                out_dir / "state_model.joblib")
    (out_dir / "model_card.json").write_text(json.dumps(card, indent=2, default=str), encoding="utf-8")
    if verbose:
        print(json.dumps({"selection": selection, "test": {k: v for k, v in metrics.items()
                                                            if k != "per_class"}}, indent=2))
    return card


if __name__ == "__main__":
    train()
